-- =====================================================================
-- V102 - Student B / Module 1 (part b): passenger services
-- =====================================================================
--   Security and boarding : point_controle_securite, controle_securite_passager,
--                           evenement_embarquement
--   Assistance and reviews: demande_assistance_passager, avis_passager
--   Customer relations    : reclamation, objet_trouve, demande_restitution_objet
--
-- Design note (normalization): assistance requests and reviews are linked to the
-- RESERVATION only. The passenger is found through reservation.passager_id, so
-- storing passager_id again would duplicate data and could become inconsistent.
-- =====================================================================

-- ---------- point_controle_securite ----------
-- A security checkpoint. "terminal" is text for now: the terminal table belongs
-- to Student A and can replace this column later with a foreign key.
CREATE TABLE point_controle_securite (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code      VARCHAR(10)  NOT NULL UNIQUE,
    nom       VARCHAR(100) NOT NULL,
    terminal  VARCHAR(20)  NOT NULL,
    type      VARCHAR(20)  NOT NULL CHECK (type IN ('STANDARD', 'PRIORITAIRE', 'EQUIPAGE')),
    actif     BOOLEAN      NOT NULL DEFAULT TRUE
);

-- ---------- controle_securite_passager ----------
-- Every pass through security. Several rows are possible for one ticket
-- (for example an extra search, then a second pass). The LAST one counts.
CREATE TABLE controle_securite_passager (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billet_id          BIGINT       NOT NULL REFERENCES billet (id),
    point_controle_id  BIGINT       NOT NULL REFERENCES point_controle_securite (id),
    resultat           VARCHAR(25)  NOT NULL
        CHECK (resultat IN ('CONFORME', 'FOUILLE_COMPLEMENTAIRE', 'REFUSE')),
    commentaire        VARCHAR(255),
    date_controle      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_controle_billet ON controle_securite_passager (billet_id);

-- ---------- evenement_embarquement ----------
-- What happens at the gate. "porte" is text for the same reason as "terminal".
CREATE TABLE evenement_embarquement (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billet_id       BIGINT       NOT NULL REFERENCES billet (id),
    type_evenement  VARCHAR(20)  NOT NULL
        CHECK (type_evenement IN ('APPEL', 'EMBARQUE', 'REFUSE', 'NON_PRESENTE')),
    porte           VARCHAR(10)  NOT NULL,
    commentaire     VARCHAR(255),
    date_evenement  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_embarquement_billet ON evenement_embarquement (billet_id);

-- A ticket can be boarded only once.
CREATE UNIQUE INDEX uq_embarquement_une_fois
    ON evenement_embarquement (billet_id)
    WHERE type_evenement = 'EMBARQUE';

-- ---------- demande_assistance_passager ----------
CREATE TABLE demande_assistance_passager (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id    BIGINT       NOT NULL REFERENCES reservation (id),
    type_assistance   VARCHAR(30)  NOT NULL
        CHECK (type_assistance IN ('FAUTEUIL_ROULANT', 'MOBILITE_REDUITE', 'MALVOYANT',
                                   'MALENTENDANT', 'MINEUR_NON_ACCOMPAGNE', 'AUTRE')),
    description       VARCHAR(500),
    statut            VARCHAR(20)  NOT NULL DEFAULT 'DEMANDEE'
        CHECK (statut IN ('DEMANDEE', 'CONFIRMEE', 'REALISEE', 'ANNULEE')),
    date_demande      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_mise_a_jour  TIMESTAMP
);

CREATE INDEX idx_assistance_reservation ON demande_assistance_passager (reservation_id);

-- No duplicate active request of the same type for the same trip.
CREATE UNIQUE INDEX uq_assistance_active
    ON demande_assistance_passager (reservation_id, type_assistance)
    WHERE statut <> 'ANNULEE';

-- ---------- avis_passager ----------
-- One review per trip, given after boarding.
CREATE TABLE avis_passager (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id  BIGINT        NOT NULL UNIQUE REFERENCES reservation (id),
    note            INTEGER       NOT NULL CHECK (note BETWEEN 1 AND 5),
    commentaire     VARCHAR(1000),
    date_avis       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- reclamation ----------
-- A complaint. The reservation and the bag are optional, but a BAGAGE complaint
-- must name the bag, and a closed complaint must contain the answer.
CREATE TABLE reclamation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference       VARCHAR(10)    NOT NULL UNIQUE,
    passager_id     BIGINT         NOT NULL REFERENCES passager (id),
    reservation_id  BIGINT         REFERENCES reservation (id),
    bagage_id       BIGINT         REFERENCES bagage (id),
    categorie       VARCHAR(25)    NOT NULL
        CHECK (categorie IN ('BAGAGE', 'RETARD_ANNULATION', 'SERVICE', 'REMBOURSEMENT', 'AUTRE')),
    sujet           VARCHAR(150)   NOT NULL,
    description     VARCHAR(2000)  NOT NULL,
    statut          VARCHAR(20)    NOT NULL DEFAULT 'OUVERTE'
        CHECK (statut IN ('OUVERTE', 'EN_COURS', 'RESOLUE', 'REJETEE')),
    reponse         VARCHAR(2000),
    date_creation   TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_cloture    TIMESTAMP,
    CONSTRAINT ck_reclamation_bagage CHECK (categorie <> 'BAGAGE' OR bagage_id IS NOT NULL),
    CONSTRAINT ck_reclamation_reponse CHECK (statut NOT IN ('RESOLUE', 'REJETEE') OR reponse IS NOT NULL)
);

CREATE INDEX idx_reclamation_passager ON reclamation (passager_id);
CREATE INDEX idx_reclamation_statut ON reclamation (statut);

-- ---------- objet_trouve ----------
CREATE TABLE objet_trouve (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference            VARCHAR(10)   NOT NULL UNIQUE,
    description          VARCHAR(255)  NOT NULL,
    categorie            VARCHAR(20)   NOT NULL
        CHECK (categorie IN ('ELECTRONIQUE', 'BAGAGERIE', 'DOCUMENT', 'VETEMENT', 'BIJOU', 'AUTRE')),
    lieu_trouve          VARCHAR(100)  NOT NULL,
    date_trouve          TIMESTAMP     NOT NULL,
    statut               VARCHAR(20)   NOT NULL DEFAULT 'EN_STOCK'
        CHECK (statut IN ('EN_STOCK', 'RESTITUE', 'ELIMINE')),
    date_enregistrement  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_sortie          TIMESTAMP
);

CREATE INDEX idx_objet_statut ON objet_trouve (statut);

-- ---------- demande_restitution_objet ----------
-- Someone claims a found object. The claimant may not be a registered passenger,
-- so passager_id is optional and the name/contact are always stored.
CREATE TABLE demande_restitution_objet (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    objet_trouve_id       BIGINT        NOT NULL REFERENCES objet_trouve (id),
    passager_id           BIGINT        REFERENCES passager (id),
    nom_demandeur         VARCHAR(160)  NOT NULL,
    contact               VARCHAR(150)  NOT NULL,
    description_preuve    VARCHAR(500)  NOT NULL,
    statut                VARCHAR(20)   NOT NULL DEFAULT 'EN_ATTENTE'
        CHECK (statut IN ('EN_ATTENTE', 'ACCEPTEE', 'REFUSEE')),
    commentaire_decision  VARCHAR(255),
    date_demande          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_decision         TIMESTAMP
);

CREATE INDEX idx_restitution_objet ON demande_restitution_objet (objet_trouve_id);

-- An object can be given back to only one person.
CREATE UNIQUE INDEX uq_restitution_acceptee
    ON demande_restitution_objet (objet_trouve_id)
    WHERE statut = 'ACCEPTEE';
