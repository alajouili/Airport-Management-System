-- V1 - TEMPORARY minimal versions of tables OWNED BY STUDENT A
-- =====================================================================
-- Student B's modules need these tables (foreign keys), but Student A
-- has not built them yet. They contain only the columns Student B uses.
--
-- When Student A delivers the real modules, Student A must NOT edit this
-- file (Flyway refuses changed scripts). Student A adds new migrations
-- (V3, V4...) with ALTER TABLE ... ADD COLUMN for the extra columns.
--
-- Convention used in every table of the project:
--   id BIGINT GENERATED BY DEFAULT AS IDENTITY  -> auto-increment primary key
--   names in French snake_case, as in the project specification
-- =====================================================================

-- ---------- auth module (Student A) ----------
CREATE TABLE role (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(50)  NOT NULL UNIQUE,
    libelle  VARCHAR(100) NOT NULL
);

CREATE TABLE utilisateur (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(150) NOT NULL UNIQUE,
    nom            VARCHAR(80)  NOT NULL,
    prenom         VARCHAR(80)  NOT NULL,
    actif          BOOLEAN      NOT NULL DEFAULT TRUE,
    date_creation  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE utilisateur_role (
    utilisateur_id  BIGINT NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    role_id         BIGINT NOT NULL REFERENCES role (id) ON DELETE CASCADE,
    PRIMARY KEY (utilisateur_id, role_id)
);

-- ---------- rh module (Student A) ----------
CREATE TABLE departement (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code  VARCHAR(20)  NOT NULL UNIQUE,
    nom   VARCHAR(100) NOT NULL
);

-- ---------- operations module (Student A) ----------
CREATE TABLE compagnie_aerienne (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_iata  VARCHAR(3)   NOT NULL UNIQUE,
    nom        VARCHAR(100) NOT NULL,
    pays       VARCHAR(60)
);

CREATE TABLE vol (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_vol          VARCHAR(10)  NOT NULL,
    compagnie_id        BIGINT       NOT NULL REFERENCES compagnie_aerienne (id),
    aeroport_depart     VARCHAR(60)  NOT NULL,
    aeroport_arrivee    VARCHAR(60)  NOT NULL,
    date_heure_depart   TIMESTAMP    NOT NULL,
    date_heure_arrivee  TIMESTAMP    NOT NULL,
    capacite            INTEGER      NOT NULL CHECK (capacite > 0),
    statut              VARCHAR(20)  NOT NULL DEFAULT 'PROGRAMME'
        CHECK (statut IN ('PROGRAMME', 'EMBARQUEMENT', 'RETARDE', 'PARTI', 'ARRIVE', 'ANNULE')),
    CONSTRAINT ck_vol_horaires CHECK (date_heure_arrivee > date_heure_depart),
    CONSTRAINT uq_vol_numero_date UNIQUE (numero_vol, date_heure_depart)
);

CREATE INDEX idx_vol_depart ON vol (date_heure_depart);
