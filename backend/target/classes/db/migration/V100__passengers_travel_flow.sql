-- =====================================================================
-- V100 - Student B / Module 1 (part a): passengers, bookings, tickets,
--        seats, check-in and baggage
-- =====================================================================
-- Flow:  passager -> reservation -> paiement -> billet -> affectation_siege_billet
--        -> enregistrement (check-in) -> bagage -> evenement / historique
--
-- Money is NUMERIC(10,3): the Tunisian dinar has 3 decimals (millimes).
-- Status columns are VARCHAR + CHECK: readable in SQL, and the database
-- itself refuses an unknown value even if the Java code has a bug.
-- =====================================================================

-- ---------- passager ----------
-- A traveller. Not necessarily a user of the application:
-- utilisateur_id is optional (filled when the passenger has an account).
CREATE TABLE passager (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom               VARCHAR(80)  NOT NULL,
    prenom            VARCHAR(80)  NOT NULL,
    email             VARCHAR(150) NOT NULL UNIQUE,
    telephone         VARCHAR(20),
    date_naissance    DATE,
    nationalite       VARCHAR(60),
    numero_passeport  VARCHAR(20) UNIQUE,
    utilisateur_id    BIGINT REFERENCES utilisateur (id),
    date_creation     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- reservation ----------
-- The commercial order: one passenger, one flight, one travel class.
CREATE TABLE reservation (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference         VARCHAR(6)    NOT NULL UNIQUE,
    passager_id       BIGINT        NOT NULL REFERENCES passager (id),
    vol_id            BIGINT        NOT NULL REFERENCES vol (id),
    classe            VARCHAR(20)   NOT NULL CHECK (classe IN ('ECONOMIQUE', 'AFFAIRES')),
    montant           NUMERIC(10,3) NOT NULL CHECK (montant >= 0),
    statut            VARCHAR(25)   NOT NULL DEFAULT 'EN_ATTENTE_PAIEMENT'
        CHECK (statut IN ('EN_ATTENTE_PAIEMENT', 'CONFIRMEE', 'ANNULEE')),
    date_reservation  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_annulation   TIMESTAMP
);

CREATE INDEX idx_reservation_vol ON reservation (vol_id);
CREATE INDEX idx_reservation_passager ON reservation (passager_id);

-- Business rule enforced by the database too: a passenger cannot hold two
-- active (non-cancelled) reservations on the same flight.
CREATE UNIQUE INDEX uq_reservation_active_passager_vol
    ON reservation (passager_id, vol_id)
    WHERE statut <> 'ANNULEE';

-- ---------- paiement ----------
-- SIMULATED payment: no card number, no bank data is ever stored.
-- Every attempt is kept (accepted or refused) for traceability.
CREATE TABLE paiement (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id         BIGINT        NOT NULL REFERENCES reservation (id),
    montant                NUMERIC(10,3) NOT NULL CHECK (montant > 0),
    mode                   VARCHAR(20)   NOT NULL CHECK (mode IN ('CARTE', 'ESPECES', 'VIREMENT')),
    statut                 VARCHAR(20)   NOT NULL CHECK (statut IN ('ACCEPTE', 'REFUSE')),
    reference_transaction  VARCHAR(30)   NOT NULL UNIQUE,
    date_paiement          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_paiement_reservation ON paiement (reservation_id);

-- Only ONE accepted payment per reservation (no double payment).
CREATE UNIQUE INDEX uq_paiement_accepte
    ON paiement (reservation_id)
    WHERE statut = 'ACCEPTE';

-- ---------- billet ----------
-- The travel document, issued automatically after an accepted payment.
CREATE TABLE billet (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_billet   VARCHAR(13) NOT NULL UNIQUE,
    reservation_id  BIGINT      NOT NULL UNIQUE REFERENCES reservation (id),
    statut          VARCHAR(20) NOT NULL DEFAULT 'EMIS'
        CHECK (statut IN ('EMIS', 'UTILISE', 'ANNULE')),
    date_emission   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- siege_avion ----------
-- Seats available on a flight. Simplification: the real model links seats
-- to the aircraft (table avion, owned by Student A). Until it exists, seats
-- are generated per flight from its capacity.
CREATE TABLE siege_avion (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vol_id  BIGINT      NOT NULL REFERENCES vol (id),
    numero  VARCHAR(4)  NOT NULL,
    classe  VARCHAR(20) NOT NULL CHECK (classe IN ('ECONOMIQUE', 'AFFAIRES')),
    CONSTRAINT uq_siege_vol_numero UNIQUE (vol_id, numero)
);

-- ---------- affectation_siege_billet ----------
-- Which seat a ticket uses. UNIQUE on both columns:
-- one seat per ticket AND one ticket per seat.
CREATE TABLE affectation_siege_billet (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billet_id         BIGINT    NOT NULL UNIQUE REFERENCES billet (id),
    siege_id          BIGINT    NOT NULL UNIQUE REFERENCES siege_avion (id),
    date_affectation  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- enregistrement ----------
-- Check-in of a ticket (at most once).
CREATE TABLE enregistrement (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    billet_id            BIGINT      NOT NULL UNIQUE REFERENCES billet (id),
    canal                VARCHAR(20) NOT NULL CHECK (canal IN ('COMPTOIR', 'EN_LIGNE', 'BORNE')),
    date_enregistrement  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- bagage ----------
CREATE TABLE bagage (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enregistrement_id  BIGINT       NOT NULL REFERENCES enregistrement (id),
    numero_etiquette   VARCHAR(12)  NOT NULL UNIQUE,
    type               VARCHAR(10)  NOT NULL CHECK (type IN ('SOUTE', 'CABINE')),
    poids_kg           NUMERIC(5,2) NOT NULL CHECK (poids_kg > 0 AND poids_kg <= 32),
    statut             VARCHAR(20)  NOT NULL DEFAULT 'ENREGISTRE'
        CHECK (statut IN ('ENREGISTRE', 'TRIE', 'CHARGE', 'DECHARGE', 'LIVRE', 'PERDU', 'RETROUVE')),
    date_creation      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_bagage_enregistrement ON bagage (enregistrement_id);

-- ---------- historique_bagage ----------
-- Audit trail: one row each time a bag changes status (written by the service).
CREATE TABLE historique_bagage (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bagage_id        BIGINT       NOT NULL REFERENCES bagage (id),
    ancien_statut    VARCHAR(20),
    nouveau_statut   VARCHAR(20)  NOT NULL,
    commentaire      VARCHAR(255),
    date_changement  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_historique_bagage ON historique_bagage (bagage_id);

-- ---------- evenement_traitement_bagage ----------
-- Physical handling events (scans). A scan can move the bag to a new status.
CREATE TABLE evenement_traitement_bagage (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bagage_id       BIGINT       NOT NULL REFERENCES bagage (id),
    type_evenement  VARCHAR(25)  NOT NULL
        CHECK (type_evenement IN ('SCAN_TRI', 'CHARGEMENT', 'DECHARGEMENT', 'LIVRAISON_TAPIS',
                                  'DECLARATION_PERTE', 'BAGAGE_RETROUVE', 'CONTROLE')),
    lieu            VARCHAR(100) NOT NULL,
    commentaire     VARCHAR(255),
    date_evenement  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_evenement_bagage ON evenement_traitement_bagage (bagage_id);
